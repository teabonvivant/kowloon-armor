import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
const file = process.argv[2] ?? '九龍裝甲行動.html';
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--disable-gpu-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await context.setOffline(true);
const page = await context.newPage(); page.setDefaultTimeout(90000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.goto(pathToFileURL(resolve(file)).href);
await page.locator('[data-mode="battle"]').first().click({ force: true });
await page.locator('[data-action="start"]').first().click({ force: true });
await page.waitForFunction(() => document.body.classList.contains('in-battle'));
await page.locator('#world').focus();
const hud = page.locator('#arcade-hud .strike');
assert.equal(await hud.count(), 1, 'strike button exists');
assert.match(await hud.textContent(), /炮擊/);
const popup = page.waitForSelector('#arcade-hud .pop.strike', { state: 'attached', timeout: 20000 });
await page.keyboard.press('KeyG'); await popup;
await page.waitForFunction(() => /\ds/.test(document.querySelector('#arcade-hud .strike')?.textContent ?? ''));
await page.keyboard.down('Space'); await page.waitForTimeout(300); await page.keyboard.up('Space');
await page.waitForTimeout(2500);
await page.screenshot({ path: '.omo/evidence/arcade-battle.png' });
assert.deepEqual(errors, []);
console.log('arcade browser ok', file);
await browser.close();
